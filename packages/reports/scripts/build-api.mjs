// Bundles the report function into ONE plain ES module so Vercel does not have to compile this workspace's TypeScript.
// Heavy or native packages stay external (Vercel installs them from package.json): sharp (native), @react-pdf/renderer, nodemailer, @supabase/supabase-js.
// Usage: node scripts/build-api.mjs [outfile]   (default: ../../api/reports.mjs). A test rebuilds it and fails if the committed file is stale.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(process.argv[2] ?? path.join(here, "../../../api/reports.mjs"));
await build({
  entryPoints: [path.join(here, "../src/vercelEntry.ts")],
  outfile: out,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["sharp", "@react-pdf/renderer", "nodemailer", "nodemailer/*", "@supabase/supabase-js", "react", "react/*"],
  jsx: "automatic",
  legalComments: "none",
  logLevel: "warning",
  banner: { js: "// GENERATED by packages/reports/scripts/build-api.mjs from packages/reports/src. Do not edit by hand." },
});
console.log("wrote", out);
